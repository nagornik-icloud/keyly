import AppKit

typealias PasteboardSnapshot = [[NSPasteboard.PasteboardType: Data]]

enum ClipboardManager {
    static func snapshot() -> PasteboardSnapshot {
        let pb = NSPasteboard.general
        return (pb.pasteboardItems ?? []).map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { dict[type] = data }
            }
            return dict
        }
    }

    static func restore(_ snapshot: PasteboardSnapshot) {
        let pb = NSPasteboard.general
        pb.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { dict -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        pb.writeObjects(items)
    }

    /// Markers clipboard managers (Paste, Maccy, Raycast) honour: don't add this entry to history.
    /// http://nspasteboard.org
    static let transientMarkers: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// `transient: true` for transport writes that are restored right after the paste —
    /// otherwise every correction and dictation piles up in the user's clipboard history.
    static func write(_ text: String, transient: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            for marker in transientMarkers { item.setData(Data(), forType: marker) }
        }
        pb.writeObjects([item])
    }

    static func read() -> String? {
        NSPasteboard.general.string(forType: .string)
    }

    /// Waits for new text to appear on the clipboard.
    /// Every `resendInterval` seconds calls `resend` to send the copy command again.
    static func waitForNewText(startCount: Int,
                               initialText: String?,
                               timeout: TimeInterval,
                               pollInterval: TimeInterval,
                               resendInterval: TimeInterval,
                               resend: () async -> Void) async -> String? {
        let deadline = Date().addingTimeInterval(timeout)
        var lastResend = Date()
        let pb = NSPasteboard.general

        while Date() < deadline {
            if let str = CopyDetection.freshText(pb.string(forType: .string),
                                                 startCount: startCount,
                                                 currentCount: pb.changeCount,
                                                 initialText: initialText) {
                return str
            }
            let now = Date()
            if now.timeIntervalSince(lastResend) >= resendInterval {
                await resend()
                lastResend = now
            }
            try? await Task.sleep(nanoseconds: UInt64(pollInterval * 1_000_000_000))
        }
        return nil
    }
}
